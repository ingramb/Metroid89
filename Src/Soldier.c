void soldier_init(SOLDIER *s, short x, short y, short angle, short hp)
{
	particle_init(&s->p, x, y, angle, 100);
	s->hp = hp;
}

void soldier_process(SOLDIER *s)
{
	PARTICLE *p = &s->p;
	short k = _rowread(ARROWS_ROW);
	short direction = -1;
	
	if((k & LEFT_KEY) && (k & UP_KEY))
		direction = 96;
	else if((k & RIGHT_KEY) && (k & UP_KEY))
		direction = 32;
	else if((k & LEFT_KEY) && (k & DOWN_KEY))
		direction = 160;
	else if((k & RIGHT_KEY) && (k & DOWN_KEY))
		direction = 224;
	else if((k & LEFT_KEY))
		direction = 128;
	else if((k & RIGHT_KEY))
		direction = 0;
	else if((k & UP_KEY))
		direction = 64;
	else if((k & DOWN_KEY))
		direction = 192;
		
	if(direction >= 0) {
		if(p->angle == direction) particle_step(p);
		else {
			if(((p->angle - direction) & 255) < 128)
				p->angle = (p->angle - 4) & 255;
			else
				p->angle = (p->angle + 4) & 255;
		}
	}
	
	if(p->x < 0) p->x = 0;
	else if(p->x >= 144) p->x = 144;
	if(p->y < 0) p->y = 0;
	else if(p->y >= 84) p->y = 84;
}

void soldier_draw(SOLDIER *s)
{
	unsigned short *f = (unsigned short *)soldier_gfx;
	short angle = s->p.angle;
	
	if(angle < 248) {
		if(angle >= 232) f += 15 * 48;
		else if(angle >= 216) f += 14 * 48;
		else if(angle >= 200) f += 13 * 48;
		else if(angle >= 184) f += 12 * 48;
		else if(angle >= 168) f += 11 * 48;
		else if(angle >= 152) f += 10 * 48;
		else if(angle >= 136) f += 9 * 48;
		else if(angle >= 120) f += 8 * 48;
		else if(angle >= 104) f += 7 * 48;
		else if(angle >= 88) f += 6 * 48;
		else if(angle >= 72) f += 5 * 48;
		else if(angle >= 56) f += 4 * 48;
		else if(angle >= 40) f += 3 * 48;
		else if(angle >= 24) f += 2 * 48;
		else if(angle >= 8) f += 1 * 48;
	}
	
	GraySprite16_MASK(s->p.x, s->p.y, 16, f, f + 16, f + 32, f + 32, light_buffer, dark_buffer);
}