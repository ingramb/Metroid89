const SCR_RECT clip = {0, 0, 239, 255};

BOX *box_create(short x, short y, short width, short hieght, void *light, void *dark)
{
	SCR_RECT rect;
	BOX *r_value;
	void *buffer;
	short size;
	short i;
	
	rect.xy.x0 = x;
	rect.xy.y0 = y;
	rect.xy.x1 = x + width - 1;
	rect.xy.y1 = y + hieght - 1;
	
	r_value = malloc(sizeof(BOX));
	
	r_value->x = x;
	r_value->y = y;
	r_value->width = width;
	r_value->hieght = hieght;
	r_value->text_hieght = (hieght - 14) / 8;
	r_value->byte_width = width / 8;
	if(r_value->byte_width * 8 < width) r_value->byte_width++;
	r_value->light = light;
	r_value->dark = dark;
	
	size = r_value->byte_width * hieght;
	
	r_value->light_save = malloc(size * 2);
	r_value->dark_save = r_value->light_save + size;
	
	SpriteX8Get(x, y, hieght, light, r_value->light_save, r_value->byte_width);
	SpriteX8Get(x, y, hieght, dark, r_value->dark_save, r_value->byte_width);
	
	PortSet(light, 239, 255);
	ScrRectFill(&rect, &clip, A_REVERSE);
	PortSet(dark, 239, 255);
	ScrRectFill(&rect, &clip, A_REVERSE);
	
	buffer = light;
	
	for(i = 0 ; i < 2 ; i++) {
		FastDrawLine(buffer, x + 3, y, x + width - 4, y, A_NORMAL);
		FastDrawLine(buffer, x + 3, y + hieght - 1, x + width - 4, y + hieght - 1, A_NORMAL);
		FastDrawLine(buffer, x, y + 3, x, y + hieght - 4, A_NORMAL);
		FastDrawLine(buffer, x + width - 1, y + 3, x + width - 1, y + hieght - 4, A_NORMAL);
		
		FastDrawLine(buffer, x + 6, y + 4, x + width - 7, y + 4, A_NORMAL);
		FastDrawLine(buffer, x + 4, y + 6, x + 4, y + hieght - 7, A_NORMAL);
		
		EXT_SETPIX(buffer, x + 1, y + 2); EXT_SETPIX(buffer, x + 2, y + 1);
		EXT_SETPIX(buffer, x + width - 2, y + 2); EXT_SETPIX(buffer, x + width - 3, y + 1);
		EXT_SETPIX(buffer, x + 1, y + hieght - 3); EXT_SETPIX(buffer, x + 2, y + hieght - 2);
		EXT_SETPIX(buffer, x + width - 2, y + hieght - 3); EXT_SETPIX(buffer, x + width - 3, y + hieght - 2);
		
		EXT_SETPIX(buffer, x + 5, y + 5);
		EXT_SETPIX(buffer, x + width - 6, y + 5);
		
		buffer = dark;
	}
	
	FastDrawLine(dark, x + 3, y + 1, x + width - 4, y + 1, A_NORMAL);
	FastDrawLine(dark, x + 1, y + 3, x + 1, y + hieght - 4, A_NORMAL);
	EXT_SETPIX(dark, x + 2, y + 2); EXT_SETPIX(dark, x + 2, y + 3); EXT_SETPIX(dark, x + 3, y + 2);
	
	EXT_SETPIX(dark, x + 2, y + hieght - 4); EXT_SETPIX(dark, x + 2, y + hieght - 3);
	EXT_SETPIX(dark, x + 3, y + hieght - 3); EXT_SETPIX(dark, x + 3, y + hieght - 2);
	
	EXT_SETPIX(dark, x + width - 4, y + 2); EXT_SETPIX(dark, x + width - 3, y + 2);
	EXT_SETPIX(dark, x + width - 3, y + 3); EXT_SETPIX(dark, x + width - 2, y + 3);
	
	EXT_SETPIX(dark, x + width - 2, y + 4);
	
	FastDrawLine(dark, x + 5, y + hieght - 4, x + width - 6, y + hieght - 4, A_NORMAL);
	FastDrawLine(dark, x + width - 4, y + 5, x + width - 4, y + hieght - 6, A_NORMAL);
	
	EXT_SETPIX(dark, x + 4, y + hieght - 6); EXT_SETPIX(dark, x + 4, y + hieght - 5);
	EXT_SETPIX(dark, x + 5, y + hieght - 5); EXT_SETPIX(dark, x + width - 6, y + hieght - 5);
	EXT_SETPIX(dark, x + width - 5, y + hieght - 5); EXT_SETPIX(dark, x + width - 5, y + hieght - 6);
	EXT_SETPIX(dark, x + width - 5, y + 5);
	
	FastDrawLine(light, x + 5, y + 3, x + width - 6, y + 3, A_NORMAL);
	FastDrawLine(light, x + 6, y + hieght - 5, x + width - 7, y + hieght - 5, A_NORMAL);
	FastDrawLine(light, x + 4, y + hieght - 2, x + width - 4, y + hieght - 2, A_NORMAL);
	FastDrawLine(light, x + 3, y + 5, x + 3, y + hieght - 6, A_NORMAL);
	FastDrawLine(light, x + width - 5, y + 6, x + width - 5, y + hieght - 7, A_NORMAL);
	FastDrawLine(light, x + width - 2, y + 5, x + width - 2, y + hieght - 4, A_NORMAL);
	
	EXT_SETPIX(light, x + 4, y + 5); EXT_SETPIX(light, x + 4, y + 4); EXT_SETPIX(light,x + 5, y + 4);
	EXT_SETPIX(light, x + 5, y + hieght - 6); EXT_SETPIX(light, x + width - 6, y + hieght - 6);
	EXT_SETPIX(light, x + width - 5, y + 4); EXT_SETPIX(light, x + width - 6, y + 4);
	EXT_SETPIX(light, x + width - 4, y + hieght - 3);
	EXT_SETPIX(light, x + width - 3, y + hieght - 3);
	EXT_SETPIX(light, x + width - 3, y + hieght - 4);
	
	return r_value;
}

inline BOX *box_create_text(short x, short y, short width, short hieght, void *light, void *dark)
{
	return box_create(x, y, width * 8 + 14, hieght * 8 + 14, light, dark);
}

void box_clear(BOX *box)
{
	SCR_RECT rect;
	
	rect.xy.x0 = box->x + 7;
	rect.xy.y0 = box->y + 7;
	rect.xy.x1 = box->x + box->width - 8;
	rect.xy.y1 = box->y + box->hieght - 8;
	
	PortSet(box->light, 239, 200);
	ScrRectFill(&rect, &clip, A_REVERSE);
	PortSet(box->dark, 239, 200);
	ScrRectFill(&rect, &clip, A_REVERSE);
}

void box_kill(BOX *box)
{
	SCR_RECT rect;
	
	rect.xy.x0 = box->x;
	rect.xy.y0 = box->y;
	rect.xy.x1 = box->x + box->width - 1;
	rect.xy.y1 = box->y + box->hieght - 1;
	
	PortSet(box->light, 239, 255);
	ScrRectFill(&rect, &clip, A_REVERSE);
	PortSet(box->dark, 239, 255);
	ScrRectFill(&rect, &clip, A_REVERSE);
	
	GraySpriteX8_OR(box->x, box->y, box->hieght, box->light_save, box->dark_save,
		box->byte_width, box->light, box->dark);
	
	free(box->light_save);
	free(box);
}

inline void draw_char(short x, short y, char c, void *light, void *dark)
{
	c -= 32;
	
	GraySprite8_OR(x, y, 8, font + 8 * c, font + 8 * c, light, dark);
}

void draw_str(short x, short y, char *s, void *light, void *dark)
{
	unsigned short i;
	
	for(i = 0 ; i < strlen(s) ; i++) {
		draw_char(x, y, s[i], light, dark);
		x += 8;
	}
}

void draw_box_num(BOX *box, short x, short y, short number)
{
	char buffer[10];
	
	sprintf(buffer, "%d", number);
	draw_box_str(box, x, y, buffer);
}

inline void draw_box_str(BOX *box, short x, short y, char *s)
{
	draw_str(box->x + 7 + x, box->y + 7 + y, s, box->light, box->dark);
}

MENU *menu_create(BOX *box, short number, short select)
{
	MENU *r_value;
	
	r_value = malloc(sizeof(MENU));
	r_value->box = box;
	r_value->number = number;
	r_value->select = select;
	r_value->top = 0;
	r_value->i = 0;
	r_value->repeat = 0;
	
	r_value->data = malloc(MENU_CHOICE_SIZE * number);
	memset(r_value->data, 0, MENU_CHOICE_SIZE * number);
	
	return r_value;
}

void menu_add_choice(MENU *menu, char *txt)
{	
	short len = strlen(txt) + 1;
	
	if(len > MENU_CHOICE_SIZE) len = MENU_CHOICE_SIZE;
	
	memcpy(menu->data + menu->i * MENU_CHOICE_SIZE, txt, len);
	menu->i++;
}

void menu_draw_hand(MENU *menu)
{	
	Sprite16Get(menu->box->x - 10, menu->box->y + (menu->select - menu->top) * 8 + 7,
		15, menu->box->light, menu->light_save);
	Sprite16Get(menu->box->x - 10, menu->box->y + (menu->select - menu->top) * 8 + 7,
		15, menu->box->dark, menu->dark_save);
	
	GraySprite16_MASK(menu->box->x - 10, menu->box->y + (menu->select - menu->top) * 8 + 7, 15,
		(unsigned short *)(hand_gfx),
		(unsigned short *)(hand_gfx + 30),
		(unsigned short *)(hand_gfx + 60),
		(unsigned short *)(hand_gfx + 60),
		menu->box->light, menu->box->dark);
}

void menu_draw(MENU *menu)
{
	short i;
	
	box_clear(menu->box);
	
	for(i = 0 ; i < menu->number ; i++) {
		if(i == menu->box->text_hieght) break;
		draw_box_str(menu->box, 0, i * 8, menu->data + (i + menu->top) * MENU_CHOICE_SIZE);
	}
	
	menu_draw_hand(menu);
}

short menu_process(MENU *menu)
{
	short k = _rowread(ARROWS_ROW);
	
	if(k == 0) {
		timer = 0;
		menu->repeat = 0;
		return MENU_NOTHING;
	}
	
	if(timer) return MENU_NOTHING;
	
	GraySprite16_BLIT(menu->box->x - 10, menu->box->y + (menu->select - menu->top) * 8 + 7, 15,
		menu->light_save, menu->dark_save, 0, menu->box->light, menu->box->dark);
	
	if(k & UP_KEY) {
		menu->select--;
		if(menu->repeat)
			timer = 35;
		else {
			timer = 250;
			menu->repeat = 1;
		}
	}
	
	if(k & DOWN_KEY) {
		menu->select++;
		if(menu->repeat)
			timer = 35;
		else {
			timer = 250;
			menu->repeat = 1;
		}
	}
	
	if(k & SEL_KEY) return MENU_SELECTED;
	if(k & DMND_KEY) return MENU_BACK;
	
	if(menu->select < 0) {
		menu->select = menu->number - 1;
		menu->top = menu->number - menu->box->text_hieght;
		if(menu->top < 0) menu->top = 0;
		menu_draw(menu);
	} else if(menu->select == menu->number) {
		menu->select = 0;
		menu->top = 0;
		menu_draw(menu);
	} else if(menu->select - menu->top < 0) {
		menu->top--;
		menu_draw(menu);
	} else if(menu->select - menu->top == menu->box->text_hieght) {
		menu->top++;
		menu_draw(menu);
	} else
		menu_draw_hand(menu);
	
	return MENU_NOTHING;
}

void menu_kill(MENU *menu)
{
	free(menu->data);
	free(menu);
}
	
	
	
	

