void draw_samus_select(short y, short frame)
{
	unsigned char *sprite1 = samus_select + frame * 153;
	unsigned char *sprite2 = sprite1 + 51;
	unsigned char *mask = sprite2 + 51;
	unsigned char *light = glbs->light_buffer + 30 * y + 6;
	unsigned char *dark = glbs->dark_buffer + 30 * y + 6;
	short h, i;

	for(h = 17 ; h ; h--) {
		*(long *)light |= 0b00111111111111111111000000000000;
		*(long *)dark |= 0b00111111111111111111000000000000;
		for(i = 0 ; i < 3 ; i++) {
			*light &= *mask; *dark &= *mask++;
			*light++ |= *sprite1++; *dark++ |= *sprite2++;
		}
		light += 27;
		dark += 27;
	}
}

void draw_title(char *buffer, short y)
{
	long *light = (long *)(glbs->light_buffer + 30 * y);
	long *dark = (long *)(glbs->dark_buffer + 30 * y);
	long *sprite0 = (long *)(buffer);
	long *sprite1 = (long *)(buffer + 78 * 20);
	long *mask = (long *)(buffer + 78 * 20 * 2);
	short i, j;

	for(i = 0 ; i < 78 ; i++) {
		for(j = 0 ; j < 5 ; j++) {
			*light &= *mask; *dark &= *mask++;
			*light++ |= *sprite0++; *dark++ |= *sprite1++;
		}
		(long)light += 10;
		(long)dark += 10;
	}
}

void draw_rect(short x, short y, short w, short h, short mode)
{
	short i;

	for(i = 0 ; i < h ; i++) {
		FastDrawHLine(glbs->light_buffer, x, x + w - 1, y + i, mode);
		FastDrawHLine(glbs->dark_buffer, x, x + w - 1, y + i, mode);
	}
}

char title_screen(char *game, void *func0, void *func1)
{
	MENU *m;
	void (*draw_energy)(short, short, short, short, void *, void *, void *, void *) = func0;
	void (*draw_time)(short, short, unsigned long) = func1;
	char *buffer;
	short i;
	SAVE_GAME *file;
	char lable[8] = "SAMUS A";
	char file_name[8] = "samus_a";
	//char select = 0;
	//char ok = TRUE, repeat;
	//short k;

	flipping_off();

	memset(glbs->light_buffer, 0xff, 3000);
	memset(glbs->dark_buffer, 0xff, 3000);
	update_screen();

	if(!ttunpack_valid(glbs->compressed_title)) return FALSE;
	
	buffer = malloc(ttunpack_size(glbs->compressed_title));
	if(!buffer) return FALSE;
	
	if(decompress(glbs->compressed_title, buffer) != TTUNPACK_OKAY) {
		free(buffer);
		return FALSE;
	}

	draw_title(buffer, 11);
	update_screen();
	pause();
	free(buffer);

	memset(glbs->light_buffer, 0xff, 3000);
	memset(glbs->dark_buffer, 0xff, 3000);
	draw_border(0, 0, 160, 100, FALSE);
	draw_border(50, 0, 60, 15, TRUE);
	draw_string(56, 5, "SAMUS DATA", glbs->font, A_NORMAL);

	m = menu_create(3);

	for(i = 0 ; i < 3 ; i++) {
		draw_border(5, 23 + 24 * i, 43, 15, TRUE);
		menu_add_choice(m, 10, 28 + 24 * i, BUTTON_DISABLE, lable);
		//draw_string(11, 28 + 24 * i, lable, font, A_NORMAL);
		draw_samus_select(22 + 24 * i, 0);
		file = file_pointer(SYMSTR(file_name));
		if(file == NULL) draw_string(70, 27 + 24 * i, "NO DATA", glbs->font, A_XOR);
		else {
			(*draw_energy)(70, 24 + 24 * i, file->player_hp, file->player_hp_max,
				glbs->light_buffer, glbs->dark_buffer, glbs->light_buffer, glbs->dark_buffer);
			draw_rect(135, 24 + i * 24, 19, 13, A_XOR);
			(*draw_time)(136, 31 + 24 * i, file->game_time);
			GraySprite16_OR(136, 25 + 24 * i, 5,
				(unsigned short *)time_lable, (unsigned short *)time_lable, glbs->light_buffer, glbs->dark_buffer);
		}
		unlock_file(file_name);
		lable[6]++;
		file_name[6]++;
	}

	menu_process(m, glbs->font);

	strcpy(game, "samus_a");
	game[6] += m->selected;

	for(i = 0 ; i < 8 ; i++) {
		glbs->timer = 50;
		draw_samus_select(22 + 24 * m->selected, i);
		update_screen();
		while(glbs->timer > 0) continue;
	}

	flipping_on();

	free(m);
	return TRUE;
}

