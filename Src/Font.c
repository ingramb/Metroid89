unsigned char *small_font;
char small_font_width[256];

void draw_char(void *buffer, char buffer_width, int x, int y, char c, short mode)
{
	if(mode == A_NORMAL)
		Sprite8_OR2(x, y + font_hieght[c - 28], 10, font + (c - 28) * 10, buffer, buffer_width);
	if(mode == A_REVERSE)
		Sprite8_REVERSE2(x, y + font_hieght[c - 28], 10, font + (c - 28) * 10, buffer, buffer_width);
}


void draw_string(short x, short y, char *text)
{
	register unsigned int i;
	
	for(i = 0 ; i < strlen(text) ; i++){
		draw_char(light_buffer, 30, x + x_buffer, y + y_buffer, *(text + i), A_NORMAL);
		draw_char(dark_buffer, 30, x + x_buffer, y + y_buffer, *(text + i), A_NORMAL);
		x += (font_width[*(text + i) - 28] + 1);
	}
}

int text_length(char *text)
{
	register unsigned char i;
	int total = 0;
	
	for(i = 0 ; i < strlen(text) ; i++)
		total += (font_width[*(text + i) - 28] + 1);
		
	return total;
}

char text_hieght(char *text)
{
	register unsigned char i;
	char hieght = 0;
	
	for(i = 0 ; i < strlen(text) ; i++)
		if(font_hieght[*(text + i) - 28] > hieght)
			hieght = font_hieght[*(text + i) - 28];
	
	return hieght + 10;
}

char init_small_font()
{
    short i;

    FontSetSys(F_4x6);
    small_font = malloc(256 * 5);
    if(small_font == NULL) return FALSE;
    memset(small_font, 0, 256 * 5);
    PortSet(small_font, 7, 5 * 256 - 1);

    for (i = 0 ; i < 256 ; i++) {
        small_font_width[i] = FontCharWidth(i);
        DrawChar(0, i*5, i, A_REPLACE);
    }
    
    return TRUE;
}

void cleanup_small_font()
{
	free(small_font);
}

void draw_small_char(void *buffer, char buffer_width, int x, int y, char c, short mode)
{
	if(mode == A_NORMAL)
		Sprite8_OR2(x, y, 5, small_font + c * 5, buffer, buffer_width);
	if(mode == A_REVERSE)
		Sprite8_REVERSE2(x, y, 5, small_font + c * 5, buffer, buffer_width);
}

