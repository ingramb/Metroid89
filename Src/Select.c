void menu_init(MENU *menu, int x, int y, int x_space, int y_space, int max)
{
	memset(menu, 0, sizeof(MENU));
	
	menu->x = x;
	menu->y = y;
	menu->x_space = x_space;
	menu->y_space = y_space;
	menu->max = max;
	menu->hand_x = x;
	menu->hand_y = y;
}

void menu_process(MENU *menu)
{
	int k;
	
	if(menu->hand_distance) {
		menu->hand_x_counter += (menu->x_space * 20);
		menu->hand_y_counter += (menu->y_space * 20);
	
		while(menu->hand_x_counter >= 100) {
			menu->hand_x += menu->hand_direction;
			menu->hand_x_counter -= 100;
		}
		
		while(menu->hand_y_counter >= 100) {
			menu->hand_y += menu->hand_direction;
			menu->hand_y_counter -= 100;
		}
		
		menu->hand_distance--;
		return;
	}
	
	k = _rowread(ARROWS_ROW);
	
	if(((k & LEFT_KEY) && menu->x_space > menu->y_space) ||
		 ((k & UP_KEY) && menu->y_space > menu->x_space)) {
				menu->select--;
				menu->hand_direction = -1;
				menu->hand_distance = 5;
	} else if(((k & RIGHT_KEY) && menu->x_space > menu->y_space) ||
		 ((k & DOWN_KEY) && menu->y_space > menu->x_space)) {
				menu->select++;
				menu->hand_direction = 1;
				menu->hand_distance = 5;
	}
	
	if(menu->select < 0) {
		menu->select = menu->max - 1;
		menu->hand_x = menu->x + menu->x_space * (menu->max - 1);
		menu->hand_y = menu->y + menu->y_space * (menu->max - 1);
		menu->hand_direction = 0;
		menu->hand_distance = 0;
	}
	
	if(menu->select == menu->max) {
		menu->select = 0;
		menu->hand_x = menu->x;
		menu->hand_y = menu->y;
		menu->hand_direction = 0;
		menu->hand_distance = 0;
	}
}

void menu_draw(MENU *menu)
{
	if(menu->x_space > menu->y_space)
		GraySprite16_MASK(menu->hand_x + x_buffer, menu->hand_y + y_buffer, 16,
			(unsigned short *)(hand), (unsigned short *)(hand + 32),
			(unsigned short *)(hand + 64), (unsigned short *)(hand + 64),
			light_buffer, dark_buffer);
	else
		GraySprite16_MASK(menu->hand_x + x_buffer, menu->hand_y + y_buffer, 16,
			(unsigned short *)(hand + 96), (unsigned short *)(hand + 96 + 32),
			(unsigned short *)(hand + 96 + 64), (unsigned short *)(hand + 96 + 64),
			light_buffer, dark_buffer);
}
