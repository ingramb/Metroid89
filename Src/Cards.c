void deck_init(DECK *deck, int deck_number)
{
	int i;
	
	deck->card_number = deck_number * 52;
	for(i = 0 ; i < 52 ; i++) deck->cards[i] = deck_number;
}

void deal(DECK *deck, HAND *hand, int *order, int hand_number)
{
	int cards_left = deck->card_number;
	int i = 0;
	int a;
	
	randomize();
	memset(hand, 0, sizeof(HAND) * hand_number);
	
	while(cards_left) {
		do {
			a = random(52);
		} while(!deck->cards[a]);
		
		deck->cards[a]--;
		cards_left--;
		
		hand[order[i]].cards[a]++;
		
		i++;
		if(i == hand_number) i = 0;
	}
}

void disp_card(int x, int y, char rank, char suit, void *light, void *dark)
{
	GraySprite16_MASK(x + x_buffer, y + y_buffer, 24,
		(unsigned short *)(card_gfx + suit * 96),
		(unsigned short *)(card_gfx + suit * 96 + 48),
		(unsigned short *)card_mask,
		(unsigned short *)card_mask,
		light, dark);
	GraySprite8_OR(x + 2 + x_buffer, y + 2 + y_buffer, 6,
		rank_gfx + 6 * rank, rank_gfx + 6 * rank, light, dark);
	GraySprite8_OR(x + 7 + x_buffer, y + 16 + y_buffer, 6,
		rank_gfx + 6 * rank, rank_gfx + 6 * rank, light, dark);
}

void disp_hand(int x, int y, HAND *hand)
{
	int i, s, r;
	int x_pos = x;
	int y_pos = y;
	int x_space;
	char had_cards;
	
	i = 0;
	for(r = 0 ; r < 13 ; r++)
		for(s = 0 ; s < 4 ; s++)
			if(hand->cards[r * 4 + s]) {
				i++;
				s += 4;
			}
	
	x_space = 160 / i;
	if(x_space > 16) x_space = 16;
	
	for(r = 0 ; r < 13 ; r++) {
		y_pos = y;
		had_cards = FALSE;
		for(s = 0 ; s < 4 ; s++)
			for(i = 0 ; i < hand->cards[r * 4 + s] ; i++) {
				disp_card(x_pos, y_pos, r, s, light_buffer, dark_buffer);
				y_pos += 8;
				had_cards = TRUE;
			}
		if(had_cards) x_pos += x_space;
	}
}
